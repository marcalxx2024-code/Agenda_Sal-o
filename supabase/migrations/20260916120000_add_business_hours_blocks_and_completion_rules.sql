-- Salon-local operating hours and exceptional schedule blocks. Timestamps stay
-- in timestamptz; weekly rules are evaluated in the salon's canonical zone.

create table public.business_hours (
  weekday smallint primary key check (weekday between 0 and 6),
  is_open boolean not null default true,
  opens_at time,
  closes_at time,
  break_starts_at time,
  break_ends_at time,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint business_hours_open_times check (
    (not is_open)
    or (opens_at is not null and closes_at is not null and opens_at < closes_at)
  ),
  constraint business_hours_break_pair check (
    (break_starts_at is null) = (break_ends_at is null)
  ),
  constraint business_hours_break_inside_opening check (
    break_starts_at is null
    or (
      is_open
      and opens_at < break_starts_at
      and break_starts_at < break_ends_at
      and break_ends_at < closes_at
    )
  )
);

-- Start permissively so applying this migration does not invalidate the salon's
-- current operation. The authorized user can configure the real week in UI.
insert into public.business_hours (weekday, is_open, opens_at, closes_at)
select weekday, true, time '00:00', time '23:59:59.999999'
from generate_series(0, 6) as weekday;

create table public.schedule_blocks (
  id bigint generated by default as identity primary key,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint schedule_blocks_valid_range check (starts_at < ends_at)
);

create index schedule_blocks_starts_at_idx on public.schedule_blocks (starts_at);
create index schedule_blocks_range_idx on public.schedule_blocks
using gist (tstzrange(starts_at, ends_at, '[)'));

